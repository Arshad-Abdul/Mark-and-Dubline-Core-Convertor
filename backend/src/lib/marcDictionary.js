export function getFieldLabel(tag) {
  if (tag === 'LDR') return 'Leader';
  return FIELD_LABELS[tag] || null;
}

export function getSubfieldLabel(tag, code) {
  return SUBFIELD_LABELS[`${tag}$${code}`] || GENERIC_SUBFIELD_LABELS[code] || FIELD_LABELS[tag] || null;
}
